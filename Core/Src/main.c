void Task_Auth(void *pvParameters) {
    uint8_t last_state = GPIO_PIN_RESET;
    for (;;) {
        uint8_t current_state = HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_0);
        if (current_state == GPIO_PIN_SET && last_state == GPIO_PIN_RESET) {
            SecurityEvent_t evt = { .type = EVENT_TOUCH_DETECTED, .timestamp = xTaskGetTickCount() };
            xQueueSend(xSecurityEventQueue, &evt, 0);
        }
        last_state = current_state;
        vTaskDelay(pdMS_TO_TICKS(50));
    }
}






void Task_Tamper(void *pvParameters) {
    for (;;) {

        if (HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13) == GPIO_PIN_RESET) {
            SecurityEvent_t evt = { .type = EVENT_IMPACT_ALERT, .timestamp = xTaskGetTickCount() };
            xQueueSend(xSecurityEventQueue, &evt, 0);
            vTaskDelay(pdMS_TO_TICKS(500));
        }
        vTaskDelay(pdMS_TO_TICKS(20));
    }
}



void Task_BCM(void *pvParameters) {
    SecurityEvent_t rx_event;
    for (;;) {
        // Block  until an event arrives in the queue
        if (xQueueReceive(xSecurityEventQueue, &rx_event, portMAX_DELAY) == pdPASS) {
            if (rx_event.type == EVENT_TOUCH_DETECTED) {
                // Relay ON for 1.5s (Door Unlocked)
                HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
                vTaskDelay(pdMS_TO_TICKS(1500));
                HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
            }
            else if (rx_event.type == EVENT_IMPACT_ALERT) {
                // Tamper alert: Rapid strobe on relay/buzzer
                for (int i = 0; i < 4; i++) {
                    HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_1);
                    vTaskDelay(pdMS_TO_TICKS(150));
                }
                HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
            }
        }
    }
}







